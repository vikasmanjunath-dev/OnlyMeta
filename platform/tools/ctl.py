"""Operator CLI: init | onboard | offboard | up | down | status | backup | restore | doctor.   python3 tools/ctl.py --help"""
import argparse
import hashlib
import json
import os
import re
import secrets
import signal
import socket
import sqlite3
import subprocess
import sys
import tarfile
import tempfile
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import yaml  # noqa: E402

from saas import envfile  # noqa: E402

ENV = Path(os.getenv("CICADA_ENV", ROOT / ".env"))
TENANTS = ROOT / "contracts/tenants.yaml"
DATA = Path(os.getenv("SAAS_DATA", ROOT / "data"))
NAME_RE, REGION_RE = re.compile(r"^[a-z][a-z0-9]{1,15}$"), re.compile(r"^[a-z]{2,8}$")
WEAK = ("change-me", "dev-key", "demo-pass", "viewer-pass")


class Fail(Exception):
    pass


def tenants() -> dict:
    return yaml.safe_load(TENANTS.read_text())["tenants"]


def tenant_vars(short: str) -> list:
    S = short.upper()
    return [f"KEY_{S}", f"USER_{S}_PASSWORD", f"USER_{S}_VIEWER_PASSWORD"]


def read_env() -> dict:
    return envfile.parse(ENV.read_text()) if ENV.is_file() else {}


def write_env(vals: dict):
    ENV.write_text("# generated by tools/ctl.py - never commit\n" + "".join(f"{k}={v}\n" for k, v in vals.items()))
    os.chmod(ENV, 0o600)


def cmd_init(a):
    vals, new = read_env(), []
    need = ["PSEUDO_KEY", "METRICS_TOKEN"] + [v for t in tenants() for v in tenant_vars(t.split("-")[-1])]
    for k in need:
        if a.force or k not in vals or any(w in vals[k] for w in WEAK):
            vals[k] = secrets.token_urlsafe(24)
            new.append(k)
    write_env(vals)
    return {"env": str(ENV), "generated": new, "note": "secrets are in the file (mode 600); read the admin passwords there"}


def cmd_onboard(a):
    if not NAME_RE.match(a.name):
        raise Fail("name must be 2-16 chars, lowercase letters/digits, starting with a letter")
    if not REGION_RE.match(a.region):
        raise Fail("region must be 2-8 lowercase letters (it names the per-region database file)")
    tid, ts = f"tenant-{a.name}", tenants()
    if tid in ts:
        raise Fail(f"{tid} already exists")
    if a.name.upper() in {t.split("-")[-1].upper() for t in ts}:
        raise Fail("name clashes with an existing tenant's env prefix")
    from zoneinfo import ZoneInfo
    try:
        ZoneInfo(a.tz)
    except Exception:
        raise Fail(f"unknown timezone {a.tz}")
    cid = a.collector_id or f"col-{a.name}-01"
    block = (f"  {tid}:\n    region: {a.region}\n    source_tz: {a.tz}\n    key_env: KEY_{a.name.upper()}\n"
             f"    collector_id: {cid}\n    ingest: \"{a.ingest}\"\n")
    txt = TENANTS.read_text()
    marker = "# SaaS stores one SQLite file"
    TENANTS.write_text(txt.replace(marker, block + marker, 1) if marker in txt else txt.rstrip("\n") + "\n" + block)
    yaml.safe_load(TENANTS.read_text())                  # still valid
    vals = read_env()
    for k in tenant_vars(a.name):
        vals[k] = secrets.token_urlsafe(24)
    vals.setdefault("PSEUDO_KEY", secrets.token_urlsafe(24))
    write_env(vals)
    n = len(ts)
    return {"tenant": tid, "region": a.region, "logins": [f"{a.name}-admin", f"{a.name}-viewer"], "secrets_in": str(ENV),
            "restart": "restart the SaaS (new region databases are created on start)",
            "collector": f"TENANT={tid} COLLECTOR_DB=data/collector_{a.name}.db python3 -m collector.main --port {8001 + n}"}


def cmd_offboard(a):
    tid = f"tenant-{a.name}"
    if tid not in tenants():
        raise Fail(f"{tid} not found")
    if len(tenants()) == 1:
        raise Fail("refusing to remove the last tenant")
    lines, out, skip = TENANTS.read_text().splitlines(keepends=True), [], False
    for ln in lines:
        if re.match(r"^  \S", ln):
            skip = ln.strip() == f"{tid}:"
        elif not ln.startswith(" ") and ln.strip():
            skip = False
        if not skip:
            out.append(ln)
    TENANTS.write_text("".join(out))
    vals = read_env()
    for k in tenant_vars(a.name):
        vals.pop(k, None)
    if ENV.is_file():
        write_env(vals)
    return {"removed": tid, "data": "kept on disk (events, audit); delete data/saas_<region>.db rows by policy, not by this tool",
            "restart": "restart the SaaS; the tenant's key and logins stop working immediately"}


RUN = DATA / "run"


def port_free(p, host="127.0.0.1"):
    with socket.socket() as s:
        return s.connect_ex((host, p)) != 0


def get(url, tok=None, timeout=2):
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {tok}"} if tok else {})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.status, r.read().decode()


def cmd_up(a):
    envfile.load(ENV)
    RUN.mkdir(parents=True, exist_ok=True)
    if (RUN / "pids.json").is_file():
        raise Fail("already running (ctl down first, or ctl status)")
    ts, plan = tenants(), []
    plan.append(("saas", [sys.executable, "-m", "saas.main", "--port", str(a.port)], {}, a.port))
    for i, tid in enumerate(ts):
        p = a.port + 1 + i
        plan.append((f"collector-{tid.split('-')[-1]}", [sys.executable, "-m", "collector.main", "--port", str(p)],
                     {"TENANT": tid, "SAAS_URL": f"http://127.0.0.1:{a.port}/ingest", "CHAOS_ORIGINS": f"http://127.0.0.1:{a.port},http://localhost:{a.port}"}, p))
    busy = [p for _, _, _, p in plan if not port_free(p)]
    if busy:
        raise Fail(f"ports in use: {busy}")
    pids = {}
    for name, argv, env, port in plan:
        log = open(DATA / f"{name}.log", "ab")
        pids[name] = {"pid": subprocess.Popen(argv, cwd=ROOT, env={**os.environ, **env}, stdout=log, stderr=subprocess.STDOUT,
                                              start_new_session=True).pid, "port": port}
    (RUN / "pids.json").write_text(json.dumps(pids))
    t0 = time.time()
    while time.time() - t0 < 30 and not all(not port_free(v["port"]) for v in pids.values()):
        time.sleep(0.3)
    if not all(not port_free(v["port"]) for v in pids.values()):
        cmd_down(a)
        raise Fail("a service did not start; see data/*.log")
    return {"started": {k: f"http://127.0.0.1:{v['port']}" for k, v in pids.items()}, "ui": f"http://127.0.0.1:{a.port}/tracker"}


def cmd_down(a):
    f = RUN / "pids.json"
    if not f.is_file():
        return {"stopped": []}
    stopped = []
    for name, v in json.loads(f.read_text()).items():
        try:
            os.killpg(v["pid"], signal.SIGTERM)
            stopped.append(name)
        except (ProcessLookupError, PermissionError):
            pass
    f.unlink()
    return {"stopped": stopped}


def cmd_status(a):
    f = RUN / "pids.json"
    if not f.is_file():
        return {"running": False}
    out = {}
    for name, v in json.loads(f.read_text()).items():
        try:
            out[name] = get(f"http://127.0.0.1:{v['port']}" + ("/healthz" if name == "saas" else "/api/status"))[0]
        except Exception as e:
            out[name] = f"down ({type(e).__name__})"
    return {"running": True, "health": out}


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def cmd_backup(a):
    out = Path(a.out or ROOT / "backups")
    out.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        files = {}
        for db in sorted(DATA.glob("*.db")):
            dst = td / db.name
            src, dc = sqlite3.connect(f"file:{db}?mode=ro", uri=True), sqlite3.connect(dst)
            src.backup(dc)                                   # online-safe, consistent snapshot
            dc.close(), src.close()
            files[db.name] = dst
        for extra in (DATA / "saas.kek", TENANTS):
            if extra.is_file():
                (td / extra.name).write_bytes(extra.read_bytes())
                files[extra.name] = td / extra.name
        man = {"created": stamp, "files": {n: {"sha256": sha(p), "bytes": p.stat().st_size} for n, p in files.items()}}
        (td / "manifest.json").write_text(json.dumps(man, indent=1))
        tgz = out / f"cicada-backup-{stamp}.tgz"
        with tarfile.open(tgz, "w:gz") as t:
            for n in [*files, "manifest.json"]:
                t.add(td / n, arcname=n)
        os.chmod(tgz, 0o600)
    return {"backup": str(tgz), "files": list(man["files"]),
            "warning": "contains saas.kek + key material: store encrypted, off this machine"}


def cmd_restore(a):
    tgz, dest = Path(a.archive), Path(a.to or DATA)
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        with tarfile.open(tgz) as t:
            for m in t.getmembers():
                if m.name != Path(m.name).name or not m.isfile():
                    raise Fail(f"unsafe path in archive: {m.name}")
            t.extractall(td, filter="data")
        man = json.loads((td / "manifest.json").read_text())
        for n, meta in man["files"].items():
            if sha(td / n) != meta["sha256"]:
                raise Fail(f"checksum mismatch: {n}")
            if n.endswith(".db"):
                c = sqlite3.connect(td / n)
                ok = c.execute("PRAGMA integrity_check").fetchone()[0]
                c.close()
                if ok != "ok":
                    raise Fail(f"integrity_check failed: {n}")
        clash = [n for n in man["files"] if n != "tenants.yaml" and (dest / n).exists()]
        if clash and not a.force:
            raise Fail(f"would overwrite {clash}; stop the services and pass --force")
        if (RUN / "pids.json").is_file() and dest == DATA:
            raise Fail("services are running; ctl down first")
        dest.mkdir(parents=True, exist_ok=True)
        for n in man["files"]:
            if n == "tenants.yaml":
                continue                                     # config is not overwritten silently
            for sfx in ("-wal", "-shm"):
                (dest / (n + sfx)).unlink(missing_ok=True)
            (dest / n).write_bytes((td / n).read_bytes())
            os.chmod(dest / n, 0o600)
    return {"restored": [n for n in man["files"] if n != "tenants.yaml"], "to": str(dest),
            "next": "ctl doctor, then ctl up; GET /api/audit/verify proves the audit chain survived"}


def cmd_doctor(a):
    res = []

    def chk(name, ok, detail=""):
        res.append({"check": name, "ok": bool(ok), "detail": detail})
    chk("python>=3.11", sys.version_info >= (3, 11), sys.version.split()[0])
    for m in ("fastapi", "uvicorn", "httpx", "pydantic", "yaml", "cryptography"):
        try:
            __import__(m)
            chk(f"import {m}", True)
        except ImportError:
            chk(f"import {m}", False, "pip install -r requirements.txt")
    vals = read_env()
    chk(".env present", ENV.is_file(), "python3 tools/ctl.py init")
    if vals:
        weak = [k for k, v in vals.items() if any(w in v for w in WEAK) or len(v) < 16]
        chk(".env secrets strong", not weak, f"weak: {weak}" if weak else "")
        miss = [k for t in tenants() for k in tenant_vars(t.split('-')[-1]) if k not in vals]
        chk(".env covers all tenants", not miss, f"missing: {miss}" if miss else "")
        chk(".env mode 600", (ENV.stat().st_mode & 0o077) == 0)
    ts = tenants()
    chk("tenants valid", all(REGION_RE.match(t["region"]) and t["key_env"] and t["collector_id"] for t in ts.values()))
    chk("collector ids unique", len({t["collector_id"] for t in ts.values()}) == len(ts))
    chk("key_env unique", len({t["key_env"] for t in ts.values()}) == len(ts))
    chk("data dir writable", os.access(DATA if DATA.exists() else ROOT, os.W_OK), str(DATA))
    for db in sorted(DATA.glob("*.db")):
        try:
            c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
            ok = c.execute("PRAGMA integrity_check").fetchone()[0]
            c.close()
        except sqlite3.Error as e:
            ok = str(e)
        chk(f"db {db.name}", ok == "ok", ok)
    ca = DATA / "tls" / "ca.pem"
    if ca.is_file():
        from cryptography import x509
        left = (x509.load_pem_x509_certificate(ca.read_bytes()).not_valid_after_utc.timestamp() - time.time()) / 86400
        chk("tls ca not expiring", left > 14, f"{left:.0f} days left")
    if (RUN / "pids.json").is_file():
        chk("running services healthy", all(str(v) == "200" for v in cmd_status(a)["health"].values()))
    return {"ok": all(r["ok"] for r in res), "checks": res}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("init", help="generate .env secrets").add_argument("--force", action="store_true", help="regenerate every secret")
    o = sp.add_parser("onboard", help="add a tenant")
    o.add_argument("name"), o.add_argument("--region", required=True), o.add_argument("--tz", default="UTC")
    o.add_argument("--collector-id"), o.add_argument("--ingest", default="https://localhost:8000/ingest")
    sp.add_parser("offboard", help="remove a tenant").add_argument("name")
    u = sp.add_parser("up", help="start SaaS + one collector per tenant")
    u.add_argument("--port", type=int, default=8000)
    sp.add_parser("down"), sp.add_parser("status")
    b = sp.add_parser("backup")
    b.add_argument("--out")
    r = sp.add_parser("restore")
    r.add_argument("archive"), r.add_argument("--to"), r.add_argument("--force", action="store_true")
    sp.add_parser("doctor")
    a = ap.parse_args(argv)
    try:
        res = globals()[f"cmd_{a.cmd}"](a)
    except Fail as e:
        print(json.dumps({"error": str(e)}))
        return 1
    print(json.dumps(res, indent=1))
    return 0 if res.get("ok", True) else 2


if __name__ == "__main__":
    sys.exit(main())
